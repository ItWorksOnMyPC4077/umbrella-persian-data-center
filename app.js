    let typingRun = 0;

    function cancelTyping() {
        typingRun++;
    }

    function typeBio(element) {
        if (!element) return;

        const run = ++typingRun;
        const reducedMotion = window.matchMedia &&
            window.matchMedia("(prefers-reduced-motion: reduce)").matches;

        if (reducedMotion) return;

        const template = document.createElement("template");
        template.innerHTML = element.innerHTML;
        const fragment = template.content;
        const walker = document.createTreeWalker(fragment, NodeFilter.SHOW_TEXT);
        const textNodes = [];
        let totalChars = 0;

        while (walker.nextNode()) {
            const node = walker.currentNode;
            const text = node.nodeValue || "";
            textNodes.push({ node, text, start: totalChars });
            totalChars += text.length;
            node.nodeValue = "";
        }

        element.replaceChildren(fragment);
        element.classList.add("is-typing");

        const typingDuration = Math.min(
            5000,
            Math.max(1200, totalChars * 9)
        );
        const startedAt = performance.now();

        function render(now) {
            if (run !== typingRun || !element.isConnected) return;

            const progress = Math.min(
                1,
                (now - startedAt) / typingDuration
            );
            const visibleChars = Math.floor(totalChars * progress);

            textNodes.forEach(part => {
                const length = Math.max(
                    0,
                    Math.min(part.text.length, visibleChars - part.start)
                );
                part.node.nodeValue = part.text.slice(0, length);
            });

            if (visibleChars < totalChars) {
                requestAnimationFrame(render);
            } else {
                setTimeout(() => {
                    if (run === typingRun) element.classList.remove("is-typing");
                }, 350);
            }
        }

        requestAnimationFrame(render);
    }

