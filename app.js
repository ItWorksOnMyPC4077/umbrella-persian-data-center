    function filterProfiles() {
        const query = document.getElementById("search-input").value.toLowerCase();
        const items = document.querySelectorAll(".sub-item");
        const menus = document.querySelectorAll(".submenu");

        items.forEach(item => {
            const originalText = item.getAttribute("data-original-text");
            if (query === "") {
                item.innerHTML = originalText;
                item.style.display = "block";
            } else if (originalText.toLowerCase().includes(query)) {
                item.style.display = "block";
                const regex = new RegExp(`(${query})`, "gi");
                item.innerHTML = originalText.replace(regex, '<span class="highlight">$1</span>');
            } else {
                item.style.display = "none";
            }
        });

        menus.forEach(menu => {
            const hasVisible = Array.from(menu.querySelectorAll(".sub-item")).some(i => i.style.display !== "none");
            if (query !== "") menu.style.display = hasVisible ? "block" : "none";
        });
    }

